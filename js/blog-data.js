function getBlogCategories() {
  const seen = new Map();

  blogPosts.forEach((post) => {
    if (!seen.has(post.category)) {
      seen.set(post.category, post.categoryLabel);
    }
  });

  return [
    { value: "all", label: "All" },
    ...Array.from(seen, ([value, label]) => ({ value, label })),
  ];
}

function getPostBySlug(slug) {
  return blogPosts.find((post) => post.slug === slug) || null;
}

function getFeaturedPost() {
  return blogPosts.find((post) => post.featured) || blogPosts[0] || null;
}

function getLatestPosts(excludeSlug) {
  return [...blogPosts]
    .filter((post) => post.slug !== excludeSlug)
    .sort((a, b) => new Date(b.date) - new Date(a.date));
}

function getRelatedPosts(post, count = 3) {
  const others = blogPosts.filter((item) => item.slug !== post.slug);
  const sameCategory = others.filter(
    (item) => item.category === post.category
  );
  const rest = others.filter(
    (item) => item.category !== post.category
  );

  return [...sameCategory, ...rest].slice(0, count);
}